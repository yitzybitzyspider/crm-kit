#!/usr/bin/env python3
"""Refuse a change that rewrites the logs, hides a skill, edits db/ by hand,
or undoes go-live.

Usage: python3 scripts/check_logs.py <base> <head> [--pr-body-file F]
       [--pr-labels-file L] [--root R]

Compares two commits. Exit 0 when fine, 1 with one line per problem, 2 when
the comparison could not be made (not a git repo, unknown commit).
The rules are written out in docs/PROTOCOL.md under "What enforces this".
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

LOGS = ("docs/DEVLOG.md", "docs/DECISIONS.md", "docs/FINDINGS.md")
SKILLS = ".claude/skills/"
# The markdown copy of the database. Only the export job writes it.
GENERATED = "db/"
EXPORT_AUTHOR = "github-actions[bot]"
EXPORT_SUBJECT = "Export:"
# The job commits with git -c user.email=..., so its committer email is this.
# The author name alone is easy to set; this is one more thing to set, not a
# proof (docs/PROTOCOL.md, rule 6).
EXPORT_EMAIL = "41898282+github-actions[bot]@users.noreply.github.com"
GENERATED_RULE = ("db/ is generated by the export job: an edit made by hand "
                  "is overwritten by the next run")


# Go-live (issue 28). hub.json saying "live": true is the record.
HUB_JSON = "hub.json"
MIGRATION_DIRS = ("app/supabase/migrations/", "app/supabase/reverts/")
HUMAN_LABEL = "needs-human-merge"
LIVE_RULE = ("the hub is live: a migration is merged by a person, after a dump. "
             "Add the label needs-human-merge")
LIVE_BACK = ("hub.json: live went from true back to false. Go-live is recorded "
             "once and is never undone by a change")


def is_live(text):
    """True only when the text is a JSON object whose live is true."""
    try:
        import json
        doc = json.loads(text)
    except ValueError:
        return False
    return isinstance(doc, dict) and doc.get("live") is True


class Unusable(Exception):
    """The comparison cannot be made at all. Exit 2."""


def make_git(root):
    env = dict(os.environ)
    for k in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"):
        env.pop(k, None)

    def git(*args, ok=(0,)):
        try:
            out = subprocess.run(["git", "-C", str(root), *args], env=env,
                                 capture_output=True, text=True)
        except OSError as e:
            raise Unusable("could not run git: %s" % e)
        if out.returncode not in ok:
            raise Unusable("git %s failed: %s"
                           % (" ".join(args), out.stderr.strip()))
        return out.returncode, out.stdout
    return git


def show(git, commit, path):
    """The file's text at that commit, or '' when it is not there."""
    code, text = git("show", "%s:%s" % (commit, path), ok=(0, 128))
    return text if code == 0 else ""


def named(skill, text):
    return re.search(r"/%s(?![\w-])" % re.escape(skill), text) is not None


def check(base, head, root=".", pr_body=None, pr_labels=None):
    """Return a list of problems. pr_body None means: do not check the body.
    pr_labels is the pull request's labels; None on a pull request counts as
    no labels."""
    if not base or set(base) == {"0"}:
        return []  # first push of a branch: nothing to compare against
    git = make_git(root)
    if not Path(root).is_dir() or git("rev-parse", "--git-dir", ok=(0, 128))[0]:
        raise Unusable("not a git repository: %s" % root)
    for c in (base, head):
        if git("rev-parse", "--verify", "-q", c + "^{commit}", ok=(0, 1, 128))[0]:
            raise Unusable("unknown commit: %s" % c)

    # Compare against where head branched off, so that work landing on the
    # base branch in the meantime is not read as removed by head.
    code, fork = git("merge-base", base, head, ok=(0, 1))
    start = fork.strip() if code == 0 and fork.strip() else base

    _, names = git("diff", "--no-renames", "--name-only", start, head)
    problems = []

    # db/ is generated. On a pull request nothing under it may change at
    # all: the export job pushes to main and never opens one. On a push,
    # every commit that changes it must be the job's own and change nothing
    # else. A merge commit is judged by what it changes against every parent,
    # so bringing the job's commits in by a merge is not read as an edit.
    if pr_body is not None:
        touched = sorted(p for p in names.splitlines() if p.startswith(GENERATED))
        if touched:
            problems.append("%s (this pull request changes %s)."
                            % (GENERATED_RULE, ", ".join(touched[:5])))
    else:
        _, revs = git("rev-list", "%s..%s" % (start, head))
        for rev in revs.split():
            _, changed = git("diff-tree", "--no-commit-id", "--name-only",
                             "--no-renames", "-r", "--root", "-c", rev)
            files = [f for f in changed.splitlines() if f]
            touched = [f for f in files if f.startswith(GENERATED)]
            if not touched:
                continue
            _, who = git("show", "-s", "--format=%an%n%ce%n%s", rev)
            author, email, subject = (who.split("\n") + ["", "", ""])[:3]
            if (author != EXPORT_AUTHOR or email != EXPORT_EMAIL
                    or not subject.startswith(EXPORT_SUBJECT)
                    or len(touched) != len(files)):
                problems.append("%s (commit %s changes %s)."
                                % (GENERATED_RULE, rev[:7], ", ".join(touched[:5])))

    added = {}
    for log in LOGS:
        _, diff = git("diff", "--no-renames", "-U0", start, head, "--", log)
        # Drop only the file header: everything before the first hunk. A
        # prefix test for "+++" or "---" would also drop real log lines that
        # begin with hyphens or plus signs. One file per diff, so one header.
        lines = diff.splitlines()
        first = next((i for i, l in enumerate(lines) if l.startswith("@@")),
                     len(lines))
        body = [l for l in lines[first:] if not l.startswith("@@")]
        added[log] = "\n".join(l[1:] for l in body if l.startswith("+"))
        removed = sum(1 for l in body if l.startswith("-"))
        if removed:
            problems.append(
                "%s: logs are append only (%d existing line%s removed or "
                "altered). Put the old lines back and add a new entry instead."
                % (log, removed, "" if removed == 1 else "s"))

    # Rules 1, 3 and 5 (a dev log entry for every system change, its format,
    # and an issue link on every pull request) were dropped by the
    # 2026-11-23 postmortem: they made a one-line fix cost a ticket. What is
    # left guards data, not paperwork.

    _, tree = git("ls-tree", "-r", "--name-only", head, "--", SKILLS)
    skills = {p[len(SKILLS):].split("/", 1)[0]: None
              for p in tree.splitlines() if "/" in p[len(SKILLS):]}
    rules = show(git, head, "CLAUDE.md")
    # Git does not record an empty directory. When head is what is checked
    # out here, also look on disk, so an empty skill folder is still caught.
    on_disk = Path(root) / SKILLS
    if (on_disk.is_dir()
            and git("rev-parse", head + "^{commit}")[1]
            == git("rev-parse", "HEAD^{commit}", ok=(0, 128))[1]):
        local = Path(root) / "CLAUDE.md"
        local_rules = local.read_text(errors="replace") if local.is_file() else ""
        for d in on_disk.iterdir():
            if d.is_dir() and d.name not in skills:
                skills[d.name] = local_rules
    for skill in sorted(skills):
        text = rules if skills[skill] is None else skills[skill]
        if not named(skill, text):
            problems.append(
                "skill /%s is not named in CLAUDE.md. Add it to the Skills "
                "list there." % skill)

    # Once live, live stays. And on a pull request against a live base, a
    # change under the migrations or reverts needs a person to merge it.
    base_live = is_live(show(git, base, HUB_JSON))
    if base_live and not is_live(show(git, head, HUB_JSON)):
        problems.append(LIVE_BACK + ".")
    if pr_body is not None and base_live:
        moved = [p for p in names.splitlines() if p.startswith(MIGRATION_DIRS)]
        if moved and HUMAN_LABEL not in (pr_labels or []):
            problems.append("%s (this pull request changes %s)." % (LIVE_RULE, ", ".join(moved[:5])))

    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("base")
    ap.add_argument("head")
    ap.add_argument("--pr-body-file")
    ap.add_argument("--pr-labels-file")
    ap.add_argument("--root", default=".")
    a = ap.parse_args(argv)
    body = None
    if a.pr_body_file is not None:
        try:
            body = Path(a.pr_body_file).read_text(errors="replace")
        except OSError:
            body = ""  # a missing body is an empty body
    labels = None
    if a.pr_labels_file is not None:
        try:
            raw = Path(a.pr_labels_file).read_text(errors="replace")
        except OSError:
            raw = ""
        # one label a line, or the JSON list GitHub gives
        try:
            import json
            parsed = json.loads(raw)
            labels = [str(x) for x in parsed] if isinstance(parsed, list) else []
        except ValueError:
            labels = [l.strip() for l in raw.splitlines() if l.strip()]
    try:
        problems = check(a.base, a.head, a.root, body, labels)
    except Unusable as e:
        print("check_logs: %s" % e, file=sys.stderr)
        return 2
    for p in problems:
        print(p)
    if problems:
        print("check_logs: %d problem%s. See docs/PROTOCOL.md, "
              "'What enforces this'." % (len(problems),
                                         "" if len(problems) == 1 else "s"))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
