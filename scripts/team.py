#!/usr/bin/env python3
"""Shared constants for the hub's scripts: the team, the outreach pipeline, name matching.

Every script imports these instead of keeping its own copy. The team, the
stakeholder categories and the canvas buckets come from team.json at the repo
root (TEAM_JSON in the environment names another file; the tests use this).

  python3 scripts/team.py sql     prints the SQL that loads team.json into the
                                  database (team members and categories). Run
                                  it once after the first migration, and again
                                  whenever team.json changes.
"""
import json
import os
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HANDLE_RE = re.compile(r"^[a-z][a-z0-9-]{1,30}$")
PREFIX_RE = re.compile(r"^[A-Z]{2}$")
SLUG_RE = re.compile(r"^[a-z][a-z0-9-]{0,40}$")


def team_path():
    return Path(os.environ.get("TEAM_JSON") or ROOT / "team.json")


def load_team(path=None):
    """team.json, checked. Raises ValueError with one plain line when it is wrong."""
    data = json.loads(Path(path or team_path()).read_text(encoding="utf-8"))
    members = data.get("members") or []
    if not members:
        raise ValueError("team.json: members is empty")
    handles, prefixes = set(), set()
    for m in members:
        h, p = m.get("handle", ""), m.get("id_prefix", "")
        if not HANDLE_RE.match(h):
            raise ValueError("team.json: handle %r must be lowercase letters, digits or -" % h)
        if not PREFIX_RE.match(p):
            raise ValueError("team.json: id_prefix %r must be two capital letters" % p)
        if h in handles or p in prefixes:
            raise ValueError("team.json: handle %r or id_prefix %r is used twice" % (h, p))
        handles.add(h)
        prefixes.add(p)
    for c in data.get("categories") or []:
        if not SLUG_RE.match(c.get("value", "")) or not c.get("label"):
            raise ValueError("team.json: category %r needs a lowercase value and a label" % c)
    for b in data.get("canvas_buckets") or []:
        if not SLUG_RE.match(b):
            raise ValueError("team.json: canvas bucket %r must be a lowercase slug" % b)
    return data


TEAM = load_team()
# handle -> ID prefix, as in team.json
ID_PREFIXES = {m["handle"]: m["id_prefix"] for m in TEAM["members"]}
HANDLES = tuple(ID_PREFIXES)
CATEGORIES = tuple(c["value"] for c in TEAM.get("categories") or [])
CANVAS_BUCKETS = tuple(TEAM.get("canvas_buckets") or [])

# Person statuses, in pipeline order.
STATUSES = ("to-contact", "contacted", "replied", "scheduled", "interviewed", "declined", "do-not-contact")
# Statuses that claim contact happened, so at least one touch file must exist.
STATUSES_NEEDING_TOUCH = ("contacted", "replied", "scheduled")

# How a touch was made.
# text is SMS, iMessage, WhatsApp and the like (issue 63).
CHANNELS = ("email", "linkedin", "phone", "text", "intro", "in-person", "other")

# Titles and credentials dropped before two names are compared.
NAME_TITLES = frozenset({"dr", "md", "rn", "np", "pa", "phd", "do", "mr", "mrs", "ms"})

# Apostrophes, straight and curly. Dropped from a name, never turned into a space.
APOSTROPHES = "['\u2018\u2019\u02bc`]"


def normalize_name(name):
    """Reduce a name to a form where two spellings of the same person are equal.

    Lowercases, folds accents to ASCII, drops titles and credentials (with or
    without periods), drops apostrophes, strips other punctuation and collapses
    spaces, so "Dr. Renée Álvarez, MD" and "renee alvarez" come out the same,
    and so do "Anne O'Neil" and "Anne ONeil".
    """
    text = unicodedata.normalize("NFKD", name)
    text = "".join(ch for ch in text if not unicodedata.combining(ch)).lower()
    text = text.replace(".", "")  # "Ph.D." becomes the single token "phd"
    text = re.sub(APOSTROPHES, "", text)  # "O'Neil" and "ONeil" are one name
    tokens = re.sub(r"[^a-z0-9]+", " ", text).split()
    return " ".join(t for t in tokens if t not in NAME_TITLES)


def _q(text):
    return "'" + str(text).replace("'", "''") + "'"


def team_sql(team=None):
    """SQL that makes the database's team_members and categories match team.json.

    Adds and updates rows; a member or category no longer in team.json is left
    in place (a person may still point at it) and named in a comment.
    """
    team = team or TEAM
    out = ["-- Generated by scripts/team.py sql from team.json. Safe to run again.", "begin;"]
    for m in team["members"]:
        out.append("insert into public.team_members (handle, id_prefix, name) values (%s, %s, %s)\n"
                   "    on conflict (handle) do update set name = excluded.name;"
                   % (_q(m["handle"]), _q(m["id_prefix"]), _q(m.get("name") or m["handle"])))
    for i, c in enumerate(team.get("categories") or []):
        out.append("insert into public.categories (value, label, position) values (%s, %s, %d)\n"
                   "    on conflict (value) do update set label = excluded.label, position = excluded.position;"
                   % (_q(c["value"]), _q(c["label"]), i))
    out.append("commit;")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] == ["sql"]:
        sys.stdout.write(team_sql())
    else:
        print("usage: python3 scripts/team.py sql", file=sys.stderr)
        sys.exit(2)
